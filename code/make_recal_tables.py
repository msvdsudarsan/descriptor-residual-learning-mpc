"""LaTeX tables of the recalibrated-physics baseline, generated from results/baseline_recal/*.csv|json (no value typed by hand).
Writes results/baseline_recal/recal_main_table.tex and supp_recal_tables.tex. Margins are those of final protocol (prediction 0.02 absolute, closed loop 2% of the mean P1* value); Student-t 95% intervals on paired run-level differences."""
import csv, json, numpy as np
from pathlib import Path
from scipy.stats import t as tdist
R = Path(__file__).resolve().parents[1] / 'results' / 'baseline_recal'
DP, DC = 0.02, 0.02
SC = ('in-family', 'saliency x1.5', 'load lag 1.0 s'); SCN = {'in-family': 'in family', 'saliency x1.5': 'saliency $\\times1.5$', 'load lag 1.0 s': 'load lag $1$\\,s'}


def tci(x):
    x = np.asarray(x, float); n = len(x); m = x.mean(); h = tdist.ppf(0.975, n - 1) * x.std(ddof=1) / np.sqrt(n); return m, h


def verdict(m, h, d):
    lo, hi = m - h, m + h
    if lo >= -d and hi <= d: return 'eq.'
    if hi < -d: return 'first'
    if lo > d: return 'second'
    return 'inc.'


def sg(x, d=3): return ('$-$' if x < 0 else '$+$') + f'{abs(x):.{d}f}'


def load(nm):
    P = {}
    for r in csv.DictReader(open(R / f'{nm}_prediction_runs.csv')): P.setdefault((r['scenario'], r['model']), {})[int(r['run'])] = (float(r['sumsq']), int(r['n']))
    C = {}
    for r in csv.DictReader(open(R / f'{nm}_closed_loop_runs.csv')): C.setdefault(r['controller'], {})[int(r['run'])] = r
    return P, C


def pred(P, scen, m):
    a0 = P[(scen, 'A0')]; return np.array([np.sqrt(P[(scen, m)][i][0] / P[(scen, m)][i][1]) / np.sqrt(a0[i][0] / a0[i][1]) for i in sorted(a0)])


def pooled(P, scen, m):
    a = P[(scen, 'A0')]; return float(np.sqrt(sum(v[0] for v in P[(scen, m)].values()) / sum(v[1] for v in P[(scen, m)].values()) / (sum(v[0] for v in a.values()) / sum(v[1] for v in a.values()))))


def main():
    sel = {nm: json.load(open(R / f'{nm}_prediction_selection.json'))['selected_P1'] for nm in ('case9', 'case39')}
    assert all(s.startswith('P1c') for s in sel.values()), 'table headers assume P1* = P1c'
    out = [r'\begin{tabular}{llcccccl}', r'\toprule', r'Case & Scenario & P1c & P2 & P3 & P2$-$P1c & $95\%$ $t$-interval & verdict\\', r'\midrule']
    for nm in ('case9', 'case39'):
        P, C = load(nm)
        for k, s in enumerate(SC):
            d = pred(P, s, 'P2 library residual') - pred(P, s, 'P1c'); m, h = tci(d)
            out.append(f'{nm if k == 0 else ""} & {SCN[s]} & {pooled(P, s, "P1c"):.3f} & {pooled(P, s, "P2 library residual"):.3f} & {pooled(P, s, "P3"):.3f} & {sg(m)} & [{m - h:+.3f}, {m + h:+.3f}] & {verdict(m, h, DP)}\\\\'.replace('[-', '[$-$').replace(', -', ', $-$'))
        if nm == 'case9': out.append(r'\midrule')
    out += [r'\bottomrule', r'\end{tabular}']
    pt = '\n'.join(out)
    out = [r'\begin{tabular}{lccccccccl}', r'\toprule', r'Case & C0 & A0 & P1c & P2 & P3 & C0eq & $E_{\rm P2}/E_{\rm C0eq}$ & P2$-$P1c & verdict\\', r'\midrule']
    for nm in ('case9', 'case39'):
        P, C = load(nm); runs = sorted(C['library residual (paper)']); g = lambda c, k='w_rms': np.array([float(C[c][i][k]) for i in runs])
        d = g('library residual (paper)') - g('P1c physical recalibration'); m, h = tci(d); dm = DC * g('P1c physical recalibration').mean()
        er = g('library residual (paper)', 'input_energy').mean() / g('C0 energy-matched', 'input_energy').mean()
        out.append(f'{nm} ($n={len(runs)}$) & ' + ' & '.join(f'{g(c).mean():.3f}' for c in ('C0 static law', 'A0 physics only', 'P1c physical recalibration', 'library residual (paper)', 'P3 residual on P1c', 'C0 energy-matched')) + f' & {er:.2f} & {sg(m, 4)}$\\pm${h:.4f} & {verdict(m, h, dm)}\\\\')
    out += [r'\bottomrule', r'\end{tabular}']
    ct = '\n'.join(out)
    (R / 'recal_main_table.tex').write_text('% generated by code/make_recal_tables.py\n' + pt + '\n%%%\n' + ct + '\n')
    # ---------------- supplement tables
    S = ['% generated by code/make_recal_tables.py']
    # D1 mismatch decomposition
    S += [r'\begin{table}[H]\centering\small', r'\caption{Decomposition of the weak-form residual target (plant minus nominal predictor acceleration) on the training trajectories (30 trajectories, seed 1001), before and after the P1c recalibration. Constant: share of the mean square carried by the per-generator mean; varying: share carried by the deviation from it. No test seed is used.}', r'\label{tab:S:decomp}',
          r'\begin{tabular}{llcccc}', r'\toprule', r'Case & loading & residual & RMS & constant & varying\\', r'\midrule']
    for r in csv.DictReader(open(R / 'mismatch_decomposition.csv')): S.append(f"{r['case']} & {r['loading']} & {r['residual']} & {float(r['rms']):.3f} & {float(r['constant_share']):.3f} & {float(r['varying_share']):.3f}\\\\")
    S += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    # D2 P1c parameter changes
    for nm in ('case9', 'case39'):
        a = list(csv.DictReader(open(R / f'{nm}_prediction_P1c_params.csv'))); b = list(csv.DictReader(open(R / f'{nm}_closed_loop_P1c_params.csv')))
        S += [r'\begin{table}[H]\centering\small', f'\\caption{{P1c recalibration on {nm}: relative change of inertia $M_i$, damping $D_i$ and mechanical power $P_{{m,i}}$ against the nominal value (percent), for the nominal-loading fit (prediction) and the elevated-loading fit (closed loop). No bound ($\\pm50\\%$) was active; solver status as reported by the optimizer (2, 3, 4: converged on gradient, cost or step tolerance).}}', f'\\label{{tab:S:p1c_{nm}}}',
              r'\begin{tabular}{lcccccccc}', r'\toprule', r' & \multicolumn{4}{c}{nominal loading} & \multicolumn{4}{c}{elevated loading}\\', r'\cmidrule(lr){2-5}\cmidrule(lr){6-9}', r'gen. & $\Delta M$ & $\Delta D$ & $\Delta P_m$ & status & $\Delta M$ & $\Delta D$ & $\Delta P_m$ & status\\', r'\midrule']
        pc = lambda r, k, k0: 100 * (float(r[k]) / float(r[k0]) - 1)
        for x, y in zip(a, b): S.append(f"{int(x['gen']) + 1} & {pc(x, 'M', 'M0'):+.1f} & {pc(x, 'D', 'D0'):+.1f} & {pc(x, 'Pm', 'P0'):+.1f} & {x['status']} & {pc(y, 'M', 'M0'):+.1f} & {pc(y, 'D', 'D0'):+.1f} & {pc(y, 'Pm', 'P0'):+.1f} & {y['status']}\\\\".replace('+', '$+$').replace('-', '$-$'))
        S += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    # D3 prediction comparisons
    S += [r'\begin{table}[H]\centering\scriptsize', r'\caption{Prediction: paired run-level differences of the one-second RMSE ratio to A0 (first model minus second), mean, $95\%$ Student-$t$ interval, margin $0.02$ and verdict (eq.: interval inside $\pm$ margin; first/second: that model is better beyond the margin; inc.: inconclusive). $n$ = runs (case9 8, case39 5).}', r'\label{tab:S:predcomp}',
          r'\begin{tabular}{lllcccl}', r'\toprule', r'Case & scenario & comparison & mean & lower & upper & verdict\\', r'\midrule']
    for nm in ('case9', 'case39'):
        P, C = load(nm)
        for s in SC:
            for a, b in (('P2 library residual', 'P1c'), ('P2 library residual', 'P1a'), ('P2 library residual', 'P1b'), ('P3', 'P1c'), ('P3', 'P2 library residual')):
                d = pred(P, s, a) - pred(P, s, b); m, h = tci(d); lab = lambda z: 'P2' if z.startswith('P2') else z
                S.append(f'{nm} & {SCN[s]} & {lab(a)}$-${lab(b)} & {m:+.4f} & {m - h:+.4f} & {m + h:+.4f} & {verdict(m, h, DP)}\\\\'.replace('+', '$+$').replace(' -', ' $-$').replace('&-', '& $-$'))
    S += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    # D4 closed loop per seed
    for nm in ('case9', 'case39'):
        P, C = load(nm); runs = sorted(C['library residual (paper)']); ctr = [('C0 static law', 'C0'), ('A0 physics only', 'A0'), ('library residual (paper)', 'P2'), ('damping + constant', 'P1a'), ('damping + cubic speed + constant', 'P1b'), ('P1c physical recalibration', 'P1c'), ('P3 residual on P1c', 'P3'), ('C0 energy-matched', 'C0eq')]
        gj = json.load(open(R / f'{nm}_c0_energy_gain.json'))
        S += [r'\begin{table}[H]\centering\small', f'\\caption{{Closed loop, {nm}: RMS speed deviation per realization (seed 6001 generator), mean input energy $E=T_s\\sum_k\\|u_k\\|^2$, and the saturation-free pilot calibration of C0eq (static gain $={gj["gain_multiple_of_D"]:.2f}\\,D$, fitted on pilot seed 80000 to the P2 pilot energy {gj["e_target"]:.3f}).}}', f'\\label{{tab:S:cl_{nm}}}',
              r'\begin{tabular}{l' + 'c' * len(runs) + r'cc}', r'\toprule', 'controller & ' + ' & '.join(f'run {i + 1}' for i in runs) + r' & mean & $E$\\', r'\midrule']
        for key, lab in ctr: S.append(f'{lab} & ' + ' & '.join(f"{float(C[key][i]['w_rms']):.4f}" for i in runs) + f" & {np.mean([float(C[key][i]['w_rms']) for i in runs]):.4f} & {np.mean([float(C[key][i]['input_energy']) for i in runs]):.2f}\\\\")
        S += [r'\midrule', r'\multicolumn{' + str(len(runs) + 3) + r'}{l}{paired differences (first minus second), $95\%$ $t$-interval, margin $=2\%$ of the second model mean; $E$ ratio = energy of first / second}\\']
        for a, b in (('library residual (paper)', 'P1c physical recalibration'), ('P3 residual on P1c', 'P1c physical recalibration'), ('P3 residual on P1c', 'library residual (paper)'), ('library residual (paper)', 'C0 energy-matched'), ('library residual (paper)', 'C0 static law')):
            d = np.array([float(C[a][i]['w_rms']) - float(C[b][i]['w_rms']) for i in runs]); m, h = tci(d); dm = DC * np.mean([float(C[b][i]['w_rms']) for i in runs]); ratio = np.mean([float(C[a][i]['input_energy']) for i in runs]) / np.mean([float(C[b][i]['input_energy']) for i in runs])
            short = {k: v for k, v in ctr}
            S.append(r'\multicolumn{' + str(len(runs) + 3) + '}{l}{' + f'{short[a]}$-${short[b]}: {m:+.4f} [{m - h:+.4f}, {m + h:+.4f}], margin {dm:.4f}, {verdict(m, h, dm)}; $E$ ratio {ratio:.3f}' .replace('+', '$+$').replace(' -', ' $-$').replace('[-', '[$-$') + r'}\\')
        S += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    (R / 'supp_recal_tables.tex').write_text('\n'.join(S) + '\n')


main()
